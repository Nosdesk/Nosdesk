/// Derive encryption key from password using PBKDF2
fn derive_key(password: &str, salt: &[u8]) -> [u8; 32] {
    let mut key = [0u8; 32];
    pbkdf2::derive(
        pbkdf2::PBKDF2_HMAC_SHA256,
        std::num::NonZeroU32::new(PBKDF2_ITERATIONS).unwrap(),
        salt,
        password.as_bytes(),
        &mut key,
    );
    key
}

/// Encrypt data using AES-256-GCM (same pattern as MFA encryption)
fn encrypt_data(data: &[u8], key: &[u8; 32]) -> Result<(Vec<u8>, [u8; NONCE_LEN]), BackupError> {
    let unbound_key = UnboundKey::new(&AES_256_GCM, key)
        .map_err(|_| BackupError::EncryptionError("Failed to create encryption key".to_string()))?;
    let sealing_key = LessSafeKey::new(unbound_key);

    // Generate random nonce
    let rng = SystemRandom::new();
    let mut nonce_bytes = [0u8; NONCE_LEN];
    rng.fill(&mut nonce_bytes)
        .map_err(|_| BackupError::EncryptionError("Failed to generate nonce".to_string()))?;
    let nonce = Nonce::assume_unique_for_key(nonce_bytes);

    // Encrypt the data
    let mut in_out = data.to_vec();
    sealing_key
        .seal_in_place_append_tag(nonce, Aad::empty(), &mut in_out)
        .map_err(|_| BackupError::EncryptionError("Encryption failed".to_string()))?;

    Ok((in_out, nonce_bytes))
}

/// Wrap a plaintext inner-zip blob in the encrypted outer
/// envelope: `NODB` magic, format version, fresh salt, fresh
/// nonce, then the AES-GCM ciphertext. The header is plaintext
/// by design so the reader can recognise the file before having
/// the password; everything that could leak schema info or row
/// counts lives inside the ciphertext.
pub(crate) fn seal_inner_zip(inner_zip: &[u8], password: &str) -> Result<Vec<u8>, BackupError> {
    let rng = SystemRandom::new();
    let mut salt = [0u8; SALT_LENGTH];
    rng.fill(&mut salt)
        .map_err(|_| BackupError::EncryptionError("Failed to generate salt".to_string()))?;

    let key = derive_key(password, &salt);
    let (ciphertext, nonce) = encrypt_data(inner_zip, &key)?;

    let mut out = Vec::with_capacity(ENCRYPTED_HEADER_LEN + ciphertext.len());
    out.extend_from_slice(ENCRYPTED_MAGIC);
    out.extend_from_slice(&BACKUP_FORMAT_VERSION.to_le_bytes());
    out.extend_from_slice(&salt);
    out.extend_from_slice(&nonce);
    out.extend_from_slice(&ciphertext);
    Ok(out)
}

/// Parse the encrypted outer envelope and return the plaintext
/// inner-zip bytes. The header is validated up front so a
/// malformed file fails fast with a clear error instead of a
/// generic decryption failure.
pub(crate) fn unseal_inner_zip(file_bytes: &[u8], password: &str) -> Result<Vec<u8>, BackupError> {
    if file_bytes.len() < ENCRYPTED_HEADER_LEN {
        return Err(BackupError::CorruptedBackup(
            "encrypted backup is shorter than its header".to_string(),
        ));
    }
    if &file_bytes[0..4] != ENCRYPTED_MAGIC {
        return Err(BackupError::CorruptedBackup(
            "missing NODB magic on encrypted backup".to_string(),
        ));
    }
    let version = u32::from_le_bytes(file_bytes[4..8].try_into().unwrap());
    if version != BACKUP_FORMAT_VERSION {
        return Err(BackupError::CorruptedBackup(format!(
            "unsupported backup format version {version}; this build expects {BACKUP_FORMAT_VERSION}"
        )));
    }
    let mut salt = [0u8; SALT_LENGTH];
    let mut nonce = [0u8; NONCE_LEN];
    salt.copy_from_slice(&file_bytes[8..8 + SALT_LENGTH]);
    nonce.copy_from_slice(&file_bytes[8 + SALT_LENGTH..ENCRYPTED_HEADER_LEN]);

    let key = derive_key(password, &salt);
    decrypt_data(&file_bytes[ENCRYPTED_HEADER_LEN..], &key, &nonce)
}

/// True when the file starts with the encrypted-wrapper magic.
/// Cheap byte check; callers use this to decide whether to
/// require a password.
pub fn is_encrypted_backup(backup_path: &Path) -> Result<bool, BackupError> {
    use std::io::Read as _;
    let mut f = File::open(backup_path)?;
    let mut magic = [0u8; 4];
    match f.read_exact(&mut magic) {
        Ok(()) => Ok(&magic == ENCRYPTED_MAGIC),
        // Shorter than 4 bytes — definitely not one of ours; let
        // the zip reader fail with its own message.
        Err(_) => Ok(false),
    }
}

/// Load the backup's inner zip bytes into memory. For plaintext
/// backups this is just the file contents; for encrypted ones
/// it's the result of unsealing the wrapper.
///
/// The whole zip lives in memory after this returns. That's
/// acceptable because the existing flow (which read every
/// `data/*.json` and `files/*` entry through `ZipArchive::by_name`)
/// already paged it all in, just with the kernel doing the work
/// instead of us.
fn load_inner_zip(backup_path: &Path, password: Option<&str>) -> Result<Vec<u8>, BackupError> {
    if is_encrypted_backup(backup_path)? {
        let bytes = fs::read(backup_path)?;
        let password = password.ok_or_else(|| {
            BackupError::EncryptionError("backup is encrypted; password is required".to_string())
        })?;
        unseal_inner_zip(&bytes, password)
    } else {
        Ok(fs::read(backup_path)?)
    }
}

/// Decrypt data using AES-256-GCM
fn decrypt_data(
    encrypted_data: &[u8],
    key: &[u8; 32],
    nonce_bytes: &[u8; NONCE_LEN],
) -> Result<Vec<u8>, BackupError> {
    let unbound_key = UnboundKey::new(&AES_256_GCM, key)
        .map_err(|_| BackupError::EncryptionError("Failed to create decryption key".to_string()))?;
    let opening_key = LessSafeKey::new(unbound_key);

    let nonce = Nonce::try_assume_unique_for_key(nonce_bytes)
        .map_err(|_| BackupError::EncryptionError("Invalid nonce".to_string()))?;

    // Decrypt
    let mut in_out = encrypted_data.to_vec();
    let plaintext = opening_key
        .open_in_place(nonce, Aad::empty(), &mut in_out)
        .map_err(|_| BackupError::InvalidPassword)?;

    Ok(plaintext.to_vec())
}

/// Export table data as JSON using raw SQL.
///
/// `table_name` is interpolated into the query directly because
/// Postgres doesn't accept identifiers as bound parameters. The
/// caller is responsible for passing only names that came from
/// `discover_user_tables`; we additionally validate against
/// `information_schema.tables` here as defence in depth so a
/// future caller can't accidentally widen the SQL-injection
/// surface.
/// Export one table's rows as a JSON-text payload. The row JSON
/// never passes through serde_json::Value, so numeric precision
/// (NUMERIC(12,3) → "10.000") is preserved verbatim. Sensitive-
/// field stripping runs inside Postgres via the `jsonb - 'key'`
/// operator.
fn export_table_data(
    conn: &mut DbConnection,
    table_name: &str,
    include_sensitive: bool,
) -> Result<(String, i64), BackupError> {
    use diesel::sql_query;
    use diesel::sql_types::Text;

    if !table_exists_in_db(conn, table_name)? {
        return Err(BackupError::CorruptedBackup(format!(
            "Refusing to export unknown table: {table_name}"
        )));
    }

    // Decide the per-row projection. With sensitive stripping,
    // the row goes through ::jsonb so the `- 'key'` operator can
    // run; back to ::text at the end for the wire format.
    let strip_fields: &[&str] = if include_sensitive {
        &[]
    } else {
        SENSITIVE_FIELDS
            .iter()
            .find(|(t, _)| *t == table_name)
            .map(|(_, fields)| *fields)
            .unwrap_or(&[])
    };

    let row_expr = if strip_fields.is_empty() {
        "row_to_json(t)::text".to_string()
    } else {
        let mut expr = "row_to_json(t)::jsonb".to_string();
        for f in strip_fields {
            // The stripped names come from the SENSITIVE_FIELDS
            // const so the value is fully under our control. We
            // still escape any embedded single quotes defensively.
            let escaped = f.replace('\'', "''");
            expr.push_str(&format!(" - '{escaped}'"));
        }
        format!("({expr})::text")
    };

    #[derive(QueryableByName)]
    struct JsonRow {
        #[diesel(sql_type = Text)]
        row_text: String,
    }

    let query = format!("SELECT {row_expr} AS row_text FROM {table_name} t");
    let results: Vec<JsonRow> = sql_query(&query).load(conn)?;

    // Assemble a JSON array as text. Each row_text is already a
    // valid JSON object (or null for empty rows, which shouldn't
    // happen). Joining with `,\n  ` keeps the on-disk format
    // mirror-image to the old pretty-printed output.
    let mut payload = String::from("[");
    for (i, row) in results.iter().enumerate() {
        if i > 0 {
            payload.push(',');
        }
        payload.push_str("\n  ");
        payload.push_str(&row.row_text);
    }
    if !results.is_empty() {
        payload.push('\n');
    }
    payload.push(']');

    let count = results.len() as i64;
    Ok((payload, count))
}

