    // ── DB-backed: poisoned-backup defence (AUD-008) ─────────────

    #[test]
    fn restore_table_data_ignores_hostile_column_names() {
        // A poisoned backup might ship a row whose JSON keys carry
        // SQL fragments instead of real column names. With the
        // pre-AUD-008 string-concatenation pattern this would have
        // landed straight in the INSERT statement. With
        // jsonb_populate_record, unknown keys are silently dropped
        // and Postgres treats them as no-ops. This test confirms:
        // (a) the legitimate column data is restored intact, and
        // (b) the hostile keys aren't executed (the users table
        //     still exists, no extra rows appear, etc).
        use crate::test_helpers::setup_test_connection;
        use diesel::prelude::*;
        use uuid::Uuid;

        let mut conn = setup_test_connection();

        let uuid = Uuid::new_v4();
        // Full row shape, matching what a real backup would
        // capture. `jsonb_populate_recordset` writes NULL for
        // missing keys, so the JSON must spell out the NOT NULL
        // columns explicitly. The hostile keys at the end are
        // what we're actually testing.
        let row = serde_json::json!({
            "uuid": uuid,
            "name": "Restored Alice",
            "platform_role": "user",
            "feature_flag_overrides": {},
            "mfa_enabled": false,
            "created_at": "2026-01-01T00:00:00",
            "updated_at": "2026-01-01T00:00:00",
            "name); DROP TABLE users; --": "ignored",
            "id, mfa_enabled) VALUES (1,true": 42,
            "); SELECT pg_sleep(60)--": null,
        });

        let payload = serde_json::to_string(&[row]).expect("serialize row");
        let inserted = restore_table_data(&mut conn, "users", &payload)
            .expect("restore_table_data should not fail");
        assert_eq!(inserted, 1, "exactly one row inserted");

        // The legit row landed with the right name.
        let name: String = crate::schema::users::table
            .filter(crate::schema::users::uuid.eq(uuid))
            .select(crate::schema::users::name)
            .first(&mut conn)
            .expect("inserted user should be readable");
        assert_eq!(name, "Restored Alice");

        // The hostile-named columns weren't created; the users table
        // shape is whatever the schema says. A simple count query
        // succeeding confirms the table wasn't dropped or mutated.
        let count: i64 = crate::schema::users::table
            .count()
            .get_result(&mut conn)
            .expect("users table should still be queryable");
        assert!(count >= 1, "users table intact after hostile insert");
    }

    /// A password-less backup restores: every sensitive column it leaves out
    /// that the schema requires has a rule, and the rules cover nothing else.
    #[test]
    fn every_required_sensitive_column_has_a_restore_rule() {
        use crate::test_helpers::setup_test_connection;
        use diesel::sql_query;
        use diesel::sql_types::Text;

        #[derive(QueryableByName)]
        struct Nullable {
            #[diesel(sql_type = Text)]
            is_nullable: String,
        }

        let mut conn = setup_test_connection();
        for (table, columns) in SENSITIVE_FIELDS {
            for column in *columns {
                let row: Nullable = sql_query(
                    "SELECT is_nullable::text AS is_nullable FROM information_schema.columns \
                     WHERE table_schema = 'public' AND table_name = $1 AND column_name = $2",
                )
                .bind::<Text, _>(*table)
                .bind::<Text, _>(*column)
                .get_result(&mut conn)
                .unwrap_or_else(|e| panic!("{table}.{column} is in the schema: {e}"));
                if row.is_nullable == "NO" {
                    assert!(
                        MISSING_COLUMNS
                            .iter()
                            .any(|m| m.table == *table && m.column == *column),
                        "{table}.{column} is NOT NULL and stripped from plaintext backups, \
                         so it needs a MISSING_COLUMNS rule"
                    );
                }
            }
        }
        for rule in MISSING_COLUMNS {
            assert!(
                SENSITIVE_FIELDS
                    .iter()
                    .any(|(t, cs)| *t == rule.table && cs.contains(&rule.column)),
                "{}.{} isn't a sensitive field; an older schema is migrated, not patched",
                rule.table,
                rule.column
            );
        }
    }
